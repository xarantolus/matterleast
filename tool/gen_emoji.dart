// Generates lib/data/emoji/emoji_table.g.dart from Mattermost's emoji.json
// (webapp/channels/src/utils/emoji.json in mattermost/mattermost).
//
//   dart run tool/gen_emoji.dart <emoji.json> [tag]
//
// The tag defaults to the first word of tool/api/server-version.
import 'dart:convert';
import 'dart:io';

const _output = 'lib/data/emoji/emoji_table.g.dart';

// Keep in step with skinToneSuffixes in lib/data/emoji/emoji.dart.
const _tones = {
  '1F3FB': '_light_skin_tone',
  '1F3FC': '_medium_light_skin_tone',
  '1F3FD': '_medium_skin_tone',
  '1F3FE': '_medium_dark_skin_tone',
  '1F3FF': '_dark_skin_tone',
};

final _namePattern = RegExp(r'^[a-z0-9_+\-]+$');
final _codePointsPattern = RegExp(r'^[0-9A-F]+(-[0-9A-F]+)*$');
final _tonedSuffix = RegExp(
  r'(_(light|medium_light|medium|medium_dark|dark)_skin_tone)+$',
);

class _Emoji {
  _Emoji(this.names, this.unified, this.category, this.skins);

  final List<String> names;
  final String unified;
  final String category;
  final List<String> skins;
  final toned = <_Emoji>[];
}

void main(List<String> args) {
  if (args.isEmpty || args.length > 2) {
    stderr.writeln('usage: dart run tool/gen_emoji.dart <emoji.json> [tag]');
    exit(64);
  }
  final tag = args.length == 2
      ? args[1]
      : File('tool/api/server-version')
            .readAsStringSync()
            .trim()
            .split(RegExp(r'\s+'))
            .first;

  final entries = jsonDecode(File(args[0]).readAsStringSync()) as List<Object?>;
  final base = <_Emoji>[];
  final toned = <_Emoji>[];
  final emoticons = <String, String>{};
  final seen = <String>{};
  var skipped = 0;

  for (final entry in entries) {
    final json = entry! as Map<String, Object?>;
    final unified = json['unified']! as String;
    // Mattermost's own logo ships as an image, not as code points.
    if (unified.isEmpty) {
      skipped++;
      continue;
    }
    final primary = json['short_name']! as String;
    final names = (json['short_names']! as List<Object?>).cast<String>();
    if (names.isEmpty || names.first != primary) {
      throw FormatException('primary name is not first: $primary');
    }
    for (final name in names) {
      if (!_namePattern.hasMatch(name) || !seen.add(name)) {
        throw FormatException('bad or duplicate name: $name');
      }
    }
    if (!_codePointsPattern.hasMatch(unified)) {
      throw FormatException('bad code points for $primary: $unified');
    }
    final skins = (json['skins'] as List<Object?>? ?? const <Object?>[])
        .cast<String>();
    if (!skins.every(_tones.containsKey)) {
      throw FormatException('unknown skin tone in $primary: $skins');
    }
    final emoji = _Emoji(names, unified, json['category']! as String, skins);
    (skins.isEmpty ? base : toned).add(emoji);

    for (final text in json['texts'] as List<Object?>? ?? const <Object?>[]) {
      emoticons.putIfAbsent(text! as String, () => primary);
    }
  }

  final byPrimary = {for (final e in base) e.names.first: e};
  for (final emoji in toned) {
    final primary = emoji.names.first;
    final parent = byPrimary[primary.replaceFirst(_tonedSuffix, '')];
    final suffix = emoji.skins.map((s) => _tones[s]).join();
    if (parent == null ||
        parent.category != emoji.category ||
        primary != '${parent.names.first}$suffix') {
      throw FormatException('toned emoji without a base: $primary');
    }
    parent.toned.add(emoji);
  }

  final categories = <String>[];
  final rows = StringBuffer();
  for (final emoji in base) {
    var index = categories.indexOf(emoji.category);
    if (index < 0) {
      index = categories.length;
      categories.add(emoji.category);
    }
    rows.writeln('$index ${emoji.unified} ${emoji.names.join(',')}');
    for (final variant in emoji.toned) {
      final tones = variant.skins
          .map((s) => _tones.keys.toList().indexOf(s) + 1)
          .join();
      final suffix = variant.skins.map((s) => _tones[s]).join();
      final derived = emoji.names.map((n) => '$n$suffix').join(',');
      final names = variant.names.join(',');
      rows.writeln(
        '~$tones ${variant.unified}${names == derived ? '' : ' $names'}',
      );
    }
  }

  String quote(String text) => text.contains("'") ? 'r"$text"' : "r'$text'";

  final out = StringBuffer()
    ..writeln(
      "// GENERATED by tool/gen_emoji.dart from Mattermost's emoji.json at "
      '$tag. Do not edit.',
    )
    ..writeln()
    ..writeln('const emojiCategories = <String>[')
    ..writeAll(categories.map((c) => "  '$c',\n"))
    ..writeln('];')
    ..writeln()
    ..writeln(
      '// One emoji per line: category index, code points, short names '
      '(primary first).',
    )
    ..writeln(
      '// Skin-tone variants follow their emoji as "~<tones 1-5> <code points>"; '
      'their',
    )
    ..writeln(
      '// names are the base names plus the tone suffixes unless listed.',
    )
    ..writeln("const emojiRows = r'''")
    ..write(rows)
    ..writeln("''';")
    ..writeln()
    ..writeln('const emoticonNames = <String, String>{')
    ..writeAll(
      emoticons.entries.map((e) => "  ${quote(e.key)}: '${e.value}',\n"),
    )
    ..writeln('};');
  File(_output)
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());

  final aliases = [
    ...base,
    ...toned,
  ].fold(0, (sum, e) => sum + e.names.length - 1);
  stdout.writeln(
    '$_output: ${base.length} emoji, ${toned.length} skin-tone variants, '
    '$aliases aliases, ${emoticons.length} emoticons, $skipped skipped',
  );
}
