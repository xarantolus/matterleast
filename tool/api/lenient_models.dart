// Writes one lenient JsonConverter per generated model (single value, list
// and map) plus the matching swagger_parser `field_parsers` entries, so that a
// nested object of the wrong shape decodes to null, [] or {} instead of
// throwing.
//
//   dart run tool/api/lenient_models.dart <models dir> <converters.dart> <parsers.yaml>
import 'dart:io';

const _package = 'matterleast';
const _modelsImport = 'package:$_package/api/generated/models';
const _convertersImport = 'package:$_package/api/json/lenient_models.dart';

final _classPattern = RegExp(r'^class (\w+) \{', multiLine: true);

void main(List<String> args) {
  if (args.length != 3) {
    stderr.writeln(
      'usage: lenient_models.dart <models dir> <converters.dart> <parsers.yaml>',
    );
    exit(2);
  }
  final files =
      Directory(args[0])
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith('.dart') && !f.path.endsWith('.g.dart'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));

  final classes = <(String, String)>[];
  for (final file in files) {
    final source = file.readAsStringSync();
    if (!source.contains('fromJson')) continue;
    final name = file.uri.pathSegments.last;
    for (final match in _classPattern.allMatches(source)) {
      classes.add((match.group(1)!, name));
    }
  }

  final dart = StringBuffer()
    ..writeln('// GENERATED by tool/api/lenient_models.dart. Do not edit.')
    ..writeln("import 'package:json_annotation/json_annotation.dart';");
  for (final (_, file) in classes) {
    dart.writeln("import '$_modelsImport/$file';");
  }
  dart.writeln("import 'package:$_package/api/json/lenient.dart';");
  final yaml = StringBuffer();
  for (final (name, _) in classes) {
    dart.write(_converters(name));
    yaml
      ..writeln(_parser('$name?', 'Lenient$name'))
      ..writeln(_parser('List<$name>', 'LenientListOf$name'))
      ..writeln(_parser('Map<String, $name>?', 'LenientMapOf$name'));
  }
  File(args[1]).writeAsStringSync(dart.toString());
  File(args[2]).writeAsStringSync(yaml.toString());
  stdout.writeln('models ${classes.length}');
}

String _parser(String type, String name) =>
    '- {apply_to_type: "$type", parser_name: $name, '
    'parser_absolute_path: "$_convertersImport"}';

String _converters(String c) =>
    '''

class Lenient$c implements JsonConverter<$c?, Object?> {
  const Lenient$c();
  @override
  $c? fromJson(Object? json) =>
      json is Map<String, Object?> ? decodeOrSkip(json, $c.fromJson) : null;
  @override
  Object? toJson($c? object) => object?.toJson();
}

class LenientListOf$c implements JsonConverter<List<$c>, Object?> {
  const LenientListOf$c();
  @override
  List<$c> fromJson(Object? json) => json is List
      ? [
          for (final e in json)
            if (e is Map<String, Object?>) ?decodeOrSkip(e, $c.fromJson),
        ]
      : const [];
  @override
  Object? toJson(List<$c> object) => [for (final e in object) e.toJson()];
}

class LenientMapOf$c implements JsonConverter<Map<String, $c>?, Object?> {
  const LenientMapOf$c();
  @override
  Map<String, $c>? fromJson(Object? json) => json is Map<String, Object?>
      ? {
          for (final e in json.entries)
            if (e.value case final Map<String, Object?> m)
              e.key: ?decodeOrSkip(m, $c.fromJson),
        }
      : null;
  @override
  Object? toJson(Map<String, $c>? object) =>
      object?.map((k, v) => MapEntry(k, v.toJson()));
}
''';
