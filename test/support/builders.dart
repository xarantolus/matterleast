import 'package:matterleast/domain/post_list.dart';

/// A post row as the channel view hands it to a tile; override what a test
/// looks at.
PostItem postItem({
  String id = 'p1',
  String userId = 'u1',
  String authorName = 'wren',
  String authorUsername = '',
  DateTime? createAt,
  String message = 'Morning',
  String? sendState,
  int replyCount = 0,
  List<ReactionGroup> reactions = const [],
  List<PostPerson> participants = const [],
  String? propsJson,
  String? metadataJson,
  bool pinned = false,
  bool saved = false,
  DateTime? editAt,
  List<PostPerson> acknowledgedBy = const [],
  DateTime? acknowledgedAt,
  bool authorIsGuest = false,
  bool authorIsBot = false,
}) => PostItem(
  id: id,
  key: id,
  userId: userId,
  authorName: authorName,
  authorUsername: authorUsername,
  createAt: createAt ?? DateTime.utc(2026, 3, 1, 9),
  message: message,
  sendState: sendState,
  replyCount: replyCount,
  reactions: reactions,
  participants: participants,
  propsJson: propsJson,
  metadataJson: metadataJson,
  pinned: pinned,
  saved: saved,
  editAt: editAt,
  acknowledgedBy: acknowledgedBy,
  acknowledgedAt: acknowledgedAt,
  authorIsGuest: authorIsGuest,
  authorIsBot: authorIsBot,
);
